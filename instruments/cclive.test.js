test('claims are read at the newest of main and origin/main, not the working tree', () => {
  const w = world();
  const root = repo(w, 'alpha', { '020-item.md': '- [ ] **T**\n' });
  // A claim on a commit origin/main has and local main does not.
  sh(w, root, ['checkout', '-q', '-b', 'side']);
  fs.writeFileSync(path.join(root, 'docs', 'roadmap', '010-area', '020-item.md'), '- [~] (claimed 2026-11-09-1312, wt: y, session aaaa1111) **T**\n');
  const later = new Date(NOW + MIN).toISOString();
  execFileSync('git', ['commit', '-q', '-am', 'claim'], { cwd: root, env: { ...w.env, GIT_COMMITTER_DATE: later } });
  sh(w, root, ['update-ref', 'refs/remotes/origin/main', 'HEAD']);
  sh(w, root, ['checkout', '-q', 'main']);
  const a = repoIn(view(w), 'alpha');
  assert.strictEqual(a.ref, 'origin/main');
  assert.strictEqual(a.claimCount, 1);
  assert.strictEqual(a.claims[0].id, '010/020');
});

