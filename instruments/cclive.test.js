// Stdlib-only tests for cclive — node:test + node:assert, zero third-party dep.
// Run:  node --test instruments/cclive.test.js
//
// Every test builds its own world in a temporary directory: throwaway git repos
// under a throwaway root, a fake HOME (so ~/.claude/projects is a fixture, never
// the real store) and an isolated git config. No test reads the real ~/.claude,
// a real repo or the network.

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync, spawnSync } = require('node:child_process');

const cl = require('./cclive');
const cc = require('./ccclose');

const SCRIPT = path.join(__dirname, 'cclive');
const MIN = 60000;
const NOW = Date.now();
const EMAIL = 't' + String.fromCharCode(64) + 'x.invalid';
const SID_A = 'aaaa1111-0000-4000-8000-000000000001';
const SID_B = 'bbbb2222-0000-4000-8000-000000000002';
const SID_DEAD = 'dead9999-0000-4000-8000-000000000003';

// --- the fixture world ---------------------------------------------------

function world() {
  const base = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'cclive-test-')));
  const home = path.join(base, 'home');
  const estate = path.join(base, 'estate');
  fs.mkdirSync(path.join(home, '.claude', 'projects'), { recursive: true });
  fs.mkdirSync(estate);
  const gitconfig = path.join(base, 'gitconfig');
  fs.writeFileSync(gitconfig, '');
  const env = {
    PATH: process.env.PATH, HOME: home, TMPDIR: os.tmpdir(),
    GIT_CONFIG_GLOBAL: gitconfig, GIT_CONFIG_NOSYSTEM: '1',
    GIT_AUTHOR_NAME: 'T', GIT_AUTHOR_EMAIL: EMAIL, GIT_COMMITTER_NAME: 'T', GIT_COMMITTER_EMAIL: EMAIL,
  };
  return { base, home, estate, env };
}

function sh(w, cwd, args) {
  return execFileSync('git', args, { cwd, env: w.env, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
}

function repo(w, name, items) {
  const root = path.join(w.estate, name);
  fs.mkdirSync(root, { recursive: true });
  sh(w, root, ['init', '-q', '-b', 'main']);
  fs.writeFileSync(path.join(root, 'README.md'), 'x\n');
  if (items) {
    fs.mkdirSync(path.join(root, 'docs', 'roadmap', '010-area'), { recursive: true });
    fs.writeFileSync(path.join(root, 'docs', 'ROADMAP.md'), '<!-- GENERATED by tools/board.py -->\n');
    for (const [file, body] of Object.entries(items)) fs.writeFileSync(path.join(root, 'docs', 'roadmap', '010-area', file), body);
  }
  sh(w, root, ['add', '-A']);
  sh(w, root, ['commit', '-q', '-m', 'init']);
  return root;
}

function transcript(w, session, lines, agoMs, agent) {
  const proj = path.join(w.home, '.claude', 'projects', 'proj');
  const dir = agent ? path.join(proj, session, 'subagents') : proj;
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, agent ? `agent-${agent}.jsonl` : `${session}.jsonl`);
  fs.writeFileSync(file, lines.map((l) => JSON.stringify(l)).join('\n') + '\n');
  const t = (NOW - agoMs) / 1000;
  fs.utimesSync(file, t, t);
  return file;
}

const cwdLine = (cwd, branch = 'main') => ({ type: 'user', cwd, gitBranch: branch });

function run(w, args, extraEnv = {}) {
  const r = spawnSync(process.execPath, [SCRIPT, ...args], { env: { ...w.env, ...extraEnv }, encoding: 'utf8' });
  return { code: r.status, out: r.stdout, err: r.stderr };
}

function view(w, args = [], extraEnv = {}) {
  const r = run(w, ['--root', w.estate, '--json', ...args], extraEnv);
  assert.strictEqual(r.code, 0, r.err);
  return JSON.parse(r.out);
}

const repoIn = (v, name) => v.repos.find((r) => r.name === name);

// --- pure parts ----------------------------------------------------------

test('parseArgs: repeats --root, validates --fresh, refuses the unknown', () => {
  assert.deepStrictEqual(cl.parseArgs(['--root', 'a', '--root', 'b', '--all']).roots, ['a', 'b']);
  assert.strictEqual(cl.parseArgs(['--fresh', '60']).fresh, 60);
  assert.ok(cl.parseArgs(['--fresh', 'soon']).error);
  assert.ok(cl.parseArgs(['--fresh', '0']).error);
  assert.ok(cl.parseArgs(['--root']).error);
  assert.ok(cl.parseArgs(['--nope']).error);
});

test('parseWorktrees: primary then linked, with detached, locked and prunable', () => {
  const list = cl.parseWorktrees([
    'worktree /r', 'HEAD 1', 'branch refs/heads/main', '',
    'worktree /w/a', 'HEAD 2', 'detached', 'locked because', '',
    'worktree /w/b', 'HEAD 3', 'branch refs/heads/x', 'prunable gone', '',
  ].join('\n'));
  assert.deepStrictEqual(list.map((x) => x.path), ['/r', '/w/a', '/w/b']);
  assert.strictEqual(list[0].branch, 'main');
  assert.ok(list[1].detached && list[1].locked && !list[1].prunable);
  assert.strictEqual(list[2].branch, 'x');
  assert.ok(list[2].prunable);
});

// git grep's shape: ref:path NUL line NUL text, for a match and its context.
const grepRow = (rel, line, text) => `main:${rel}\0${line}\0${text}`;
const ITEMS = 'docs/roadmap';
const RM = `${ITEMS}/010-area/020-item.md`;

test('parseClaims: a stamp wrapped to line 2 dates the claim and names its session and worktree', () => {
  const out = [grepRow(RM, 1, '- [~] 🎯 **A title that'), grepRow(RM, 2, '      wraps** (claimed 2026-11-09-1312, wt: wa-live; session aaaa1111, worker)')].join('\n');
  const [c] = cl.parseClaims(out, 'main', ITEMS, NOW);
  assert.strictEqual(c.id, '010/020');
  assert.ok(c.dated);
  assert.strictEqual(c.claimedAt, '2026-11-09T13:12:00.000Z');
  assert.strictEqual(c.session, 'aaaa1111');
  assert.strictEqual(c.worktree, 'wa-live');
  assert.strictEqual(c.title, '🎯 A title that wraps');
});

test('parseClaims: the paragraph ends at a block start, so a sub-bullet stamp is not the item\'s', () => {
  const out = [grepRow(RM, 1, '- [~] **Title**'), grepRow(RM, 2, '  - a sub-bullet (claimed 2026-01-01-0000)')].join('\n');
  const [c] = cl.parseClaims(out, 'main', ITEMS, NOW);
  assert.ok(!c.dated);
});

test('parseClaims: left-margin undated counts; indented undated is a progress mark; indented stamped counts', () => {
  const out = [
    grepRow(RM, 1, '- [~] **Undated state line**'),
    grepRow(RM, 5, '  - [~] a sub-bullet in progress'),
    grepRow(RM, 9, '  - [~] (claimed 2026-11-03 0941Z by session `name-96` (bead1234), rest'),
  ].join('\n');
  const claims = cl.parseClaims(out, 'main', ITEMS, NOW);
  assert.deepStrictEqual(claims.map((c) => c.id), ['010/020', '010/020:9']);
  assert.ok(!claims[0].dated);
  assert.ok(claims[1].dated);
  assert.strictEqual(claims[1].session, 'bead1234');
});

test('parseClaims: a released stamp does not date a claim, a compact date is not a session', () => {
  const out = [grepRow(RM, 1, '- [~] **Title**'), grepRow(RM, 2, '      🔓 Claimed 2026-11-01 15:32 UTC (released at the close)')].join('\n');
  assert.ok(!cl.parseClaims(out, 'main', ITEMS, NOW)[0].dated);
  const date = cl.parseClaims(grepRow(RM, 1, '- [~] (claimed 2026-11-09-1312, ref 20261109) **T**'), 'main', ITEMS, NOW)[0];
  assert.strictEqual(date.session, null);
});

test('parseClaims: the upper-case form and a date with no time', () => {
  const a = cl.parseClaims(grepRow(RM, 1, '- [~] 🔒 CLAIMED 2026-11-09 12:42 UTC, session cafe0123, wt: x **T**'), 'main', ITEMS, NOW)[0];
  assert.strictEqual(a.claimedAt, '2026-11-09T12:42:00.000Z');
  assert.strictEqual(a.session, 'cafe0123');
  assert.strictEqual(a.worktree, 'x');
  const b = cl.parseClaims(grepRow(RM, 1, '- [~] (claimed 2026-10-01, wt: y) **T**'), 'main', ITEMS, NOW)[0];
  assert.strictEqual(b.claimedAt, '2026-10-01T00:00:00.000Z');
  assert.strictEqual(b.title, 'T');
});

