// Stdlib-only tests for ccopen — node:test + node:assert, zero third-party dep.
// Run:  node --test instruments/ccopen.test.js
//
// Every test builds its own world in a temporary directory: throwaway git repos
// with a local bare origin, a fake HOME (so ~/.claude/projects is a fixture,
// never the real store), an isolated git config, synthetic transcripts, and a
// stub standing in for `gh` through $CCCLOSE_GH (ccopen reuses ccclose's seams).
// No test reads the real ~/.claude, a real repo or the network.

