const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync, spawnSync } = require('node:child_process');

const co = require('./ccopen');

const SCRIPT = path.join(__dirname, 'ccopen');
const TOOLS = path.join(__dirname, '..', 'tools');
const MIN = 60000;
const NOW = Date.now();
// A synthetic identity, spelled so no scanner reads it as a real address.
const EMAIL = 't' + String.fromCharCode(64) + 'x.invalid';
const SELF = 'aaaa1111-0000-4000-8000-000000000001';
const OTHER = 'bbbb2222-0000-4000-8000-000000000002';
const DEAD = 'dead0001-0000-4000-8000-000000000003';
const READ_IDS = ['kind', 'sync', 'live', 'interrupted', 'handups', 'pin', 'files', 'load', 'waiting'];

// --- the fixture world ---------------------------------------------------

function world() {
  // realpath: a transcript's cwd is matched to a worktree by real path, and the
  // temp dir is a symlink on macOS.
  const base = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'ccopen-test-')));
  const home = path.join(base, 'home');
  fs.mkdirSync(path.join(home, '.claude', 'projects', 'proj'), { recursive: true });
  const gitconfig = path.join(base, 'gitconfig');
  fs.writeFileSync(gitconfig, '');
  const env = {
    PATH: process.env.PATH, HOME: home, TMPDIR: os.tmpdir(),
    GIT_CONFIG_GLOBAL: gitconfig, GIT_CONFIG_NOSYSTEM: '1',
    GIT_AUTHOR_NAME: 'T', GIT_AUTHOR_EMAIL: EMAIL, GIT_COMMITTER_NAME: 'T', GIT_COMMITTER_EMAIL: EMAIL,
    CCCLOSE_GH: path.join(base, 'no-gh-here'),
    // No atelier checkout unless a test points one: the pin read must say so.
    CCCLOSE_ATELIER: path.join(base, 'no-atelier-here'),
    // A quiet machine unless a test says otherwise: the real load average must
    // never decide whether a fixture reads as ready (180/220).
    CCOPEN_LOADAVG: '0.10,0.10,0.10', CCOPEN_CORES: '4',
  };
  return { base, home, env };
}

function sh(w, cwd, args) {
  return execFileSync('git', args, { cwd, env: w.env, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
}
function write(root, rel, text) {
  const p = path.join(root, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, text);
}
function commit(w, root, msg) {
  sh(w, root, ['add', '--', '.']);
  sh(w, root, ['commit', '-q', '-m', msg]);
  return sh(w, root, ['rev-parse', 'HEAD']);
}
// A repo on main with one commit, pushed to a local bare origin.
function repo(w, name = 'repo') {
  const root = path.join(w.base, name);
  const bare = path.join(w.base, `${name}.git`);
  fs.mkdirSync(root);
  sh(w, w.base, ['init', '-q', '--bare', '-b', 'main', bare]);
  sh(w, root, ['init', '-q', '-b', 'main']);
  sh(w, root, ['remote', 'add', 'origin', bare]);
  write(root, 'README.md', 'demo\n');
  commit(w, root, 'init');
  sh(w, root, ['push', '-q', '-u', 'origin', 'main']);
  sh(w, root, ['remote', 'set-head', 'origin', 'main']);
  return root;
}
// Land a commit on origin from another clone, so root's ref is stale until a fetch.
function pushElsewhere(w, root, file = 'peer.txt') {
  const bare = path.join(w.base, `${path.basename(root)}.git`);
  const other = fs.mkdtempSync(path.join(w.base, 'peer-'));
  sh(w, w.base, ['clone', '-q', bare, other]);
  write(other, file, 'from a peer\n');
  commit(w, other, `peer adds ${file}`);
  sh(w, other, ['push', '-q', 'origin', 'main']);
  return sh(w, other, ['rev-parse', 'HEAD']);
}
// Make a repo read as atelier itself, or as a child pinned at an atelier sha.
function asAtelier(w, root) {
  write(root, 'tools/pins.py', '# stand-in\n');
  write(root, 'docs/method/PROPAGATION.md', '# propagation\n');
  commit(w, root, 'atelier markers');
  sh(w, root, ['push', '-q', 'origin', 'main']);
}
function asChild(w, root, sha = 'abc1234def') {
  write(root, 'CLAUDE.md', `# child\n\nDoctrine pinned \`atelier@${sha}\`.\n`);
  commit(w, root, 'claude');
  sh(w, root, ['push', '-q', 'origin', 'main']);
}
// A generated board with one item file per entry, committed and pushed.
function withBoard(w, root, items) {
  write(root, 'docs/ROADMAP.md', '<!-- GENERATED by tools/board.py -->\n# Board\n');
  Object.entries(items).forEach(([name, text]) => write(root, `docs/roadmap/010-area/${name}`, text));
  commit(w, root, 'board');
  sh(w, root, ['push', '-q', 'origin', 'main']);
}

// A transcript for `session` working in `cwd`, written `agoMs` ago.
function transcript(w, session, cwd, agoMs = 0) {
  const file = path.join(w.home, '.claude', 'projects', 'proj', `${session}.jsonl`);
  fs.writeFileSync(file, `${JSON.stringify({ type: 'user', cwd, gitBranch: 'main' })}\n${JSON.stringify({ type: 'ai-title', aiTitle: 'Some other work' })}\n`);
  const t = (NOW - agoMs) / 1000;
  fs.utimesSync(file, t, t);
  return file;
}

// A gh stub: auth status and `pr list` from a JSON file.
function ghStub(w, { prs = [], authOk = true, listOk = true } = {}) {
  const dir = path.join(w.base, 'gh');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'prs.json'), JSON.stringify(prs));
  const stub = path.join(dir, 'gh');
  fs.writeFileSync(stub, `#!/bin/sh
case "$1 $2" in
  "auth status") ${authOk ? 'exit 0' : 'exit 1'} ;;
  "pr list") ${listOk ? `cat "${dir}/prs.json"` : 'exit 1'} ;;
  *) exit 2 ;;
esac
`);
  fs.chmodSync(stub, 0o755);
  return stub;
}
const githubRemote = (w, root) => sh(w, root, ['remote', 'set-url', 'origin', 'https://github.com/example/demo.git']);
const pr = (number, title, head, body) => ({ number, title, headRefName: head, ...(body === undefined ? {} : { body }), createdAt: new Date(NOW).toISOString(), url: `https://example.invalid/pull/${number}` });

function ccopen(w, cwd, args = [], envExtra = {}) {
  const r = spawnSync('node', [SCRIPT, ...args], { cwd, env: { ...w.env, ...envExtra }, encoding: 'utf8' });
  return { code: r.status, out: r.stdout, err: r.stderr };
}
function json(w, cwd, args = [], envExtra = {}) {
  const r = ccopen(w, cwd, ['--json', ...args], envExtra);
  assert.ok(r.out, `no output: ${r.err}`);
  const j = JSON.parse(r.out);
  j.code = r.code;
  j.by = Object.fromEntries(j.reads.map((x) => [x.id, x]));
  return j;
}

