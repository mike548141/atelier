test('it is read-only: nothing in the repo changes, no lock is taken, and --no-fetch moves no ref', () => {
  const w = world();
  const root = repo(w);
  write(root, 'dirty.txt', 'x\n');
  const snap = () => [sh(w, root, ['status', '--porcelain']), sh(w, root, ['for-each-ref']), sh(w, root, ['stash', 'list']), fs.existsSync(path.join(root, '.git', 'index.lock'))].join('|');
  const before = snap();
  pushElsewhere(w, root);
  const staleRefs = snap();
  ccopen(w, root, ['--no-fetch']);
  assert.equal(snap(), staleRefs, 'no ref moved under --no-fetch');
  assert.equal(staleRefs, before);
  ccopen(w, root, []);
  assert.notEqual(sh(w, root, ['rev-parse', 'origin/main']), sh(w, root, ['rev-parse', 'main']), 'the fetch (and only the fetch) moved origin/main');
  assert.equal(sh(w, root, ['status', '--porcelain']), '?? dirty.txt', 'the working tree is untouched by the fetch');
});

