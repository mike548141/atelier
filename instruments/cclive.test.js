test('a claim is live on a positive match by session or worktree; otherwise quiet', () => {
  const w = world();
  const root = repo(w, 'alpha', {
    '020-a.md': '- [~] (claimed 2026-11-09-1312, wt: wt-x, session aaaa1111) **By a live session**\n',
    '030-b.md': '- [~] (claimed 2026-11-09-1312, wt: wt-gone, session dead9999) **By a dead session**\n',
    '040-c.md': '- [~] (claimed 2026-11-09-1312, wt: wt-y) **Worktree has a live session**\n',
  });
  const wx = path.join(w.base, 'wt-x');
  const wy = path.join(w.base, 'wt-y');
  sh(w, root, ['worktree', 'add', '-q', '-b', 'x', wx]);
  sh(w, root, ['worktree', 'add', '-q', '-b', 'y', wy]);
  transcript(w, SID_A, [cwdLine(root)], MIN);
  transcript(w, SID_B, [cwdLine(wy)], MIN);
  const a = repoIn(view(w), 'alpha');
  const live = Object.fromEntries(a.claims.map((c) => [c.id, c.live]));
  assert.deepStrictEqual(live, { '010/020': true, '010/030': false, '010/040': true });
  const wts = Object.fromEntries(a.worktrees.map((t) => [t.name, t.live]));
  // wt-x has no session in its cwd; a claim by a live session names it.
  assert.deepStrictEqual(wts, { 'wt-x': true, 'wt-y': true });
});

